  @visibleForTesting
  static String giftLanguageCodeForLocale(ui.Locale locale) {
    final String languageTag = locale.toLanguageTag().replaceAll('_', '-').toLowerCase();
    if (languageTag != 'zh' && !languageTag.startsWith('zh-')) {
      return 'en';
    }
    if (languageTag == 'zh' ||
        languageTag.contains('hans') ||
        languageTag.startsWith('zh-cn') ||
        languageTag.startsWith('zh-sg') ||
        languageTag.startsWith('zh-my')) {
      return 'zh-Hans';
    }
    return 'zh-Hant';
  }

